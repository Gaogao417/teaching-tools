/** Offline production Canvas H24: live resize/zoom after a real render receipt. */
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
const require = createRequire(new URL('../package.json', import.meta.url));
const { chromium } = require('@playwright/test');
const [url = 'http://127.0.0.1:5195', output = '/private/tmp/visual-canvas-evidence'] = process.argv.slice(2);
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
 const page = await browser.newPage({ viewport: { width: 1100, height: 850 } });
 await page.route("**/__visual_canvas_h24", route => route.fulfill({ contentType: "text/html", body: "<!doctype html><html><body></body></html>" }));
 await page.goto(`${url}/__visual_canvas_h24`);
 const result = await page.evaluate(async () => {
  const { default: RefreshRuntime } = await import('/@react-refresh');
  RefreshRuntime.injectIntoGlobalHook(window);
  window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type;
  window.__vite_plugin_react_preamble_installed__ = true;
  const { default: React } = await import('/node_modules/.vite/deps/react.js');
  const { default: ReactDOM } = await import('/node_modules/.vite/deps/react-dom_client.js');
  const { createRoot } = ReactDOM;
  const { GeometryCanvasSurface } = await import('/src/geometry/react/GeometryCanvas.tsx');
  const { GeometryModel } = await import('/src/geometry/domain/model.ts');
  const { createWorkspaceCommitPort } = await import('/src/presentation/presentationRuntime/workspaceCommitPort.ts');
  const boardModule = await (await fetch('/src/geometry/react/jsxgraph-board.ts')).text();
  const boardImport = boardModule.match(/from ["']([^"']*jsxgraph\.js[^"']*)["']/)[1];
  const { default: JXG } = await import(boardImport);
  const host = document.createElement('div'); document.body.replaceChildren(host);
  host.style.cssText = 'width:700px;height:500px;position:relative';
  const style = document.createElement('style');
  style.textContent = '.geometry-canvas{width:100%;height:100%;position:relative}.geometry-canvas__board{width:100%;height:100%;position:relative}'; document.head.appendChild(style);
  const model = new GeometryModel({points:[{id:'A',x:0,y:0},{id:'B',x:10,y:0},{id:'C',x:0,y:8}],lines:[{id:'AB',kind:'segment',from:'A',to:'B'}]});
  const port = createWorkspaceCommitPort();
  const root = createRoot(host);
  let mounted; const ready = new Promise(resolve => mounted=resolve);
  root.render(React.createElement(GeometryCanvasSurface,{model,modelVersion:0,view:{prompt:'',accepts:[],selected:[],entities:{}},onClickEntity:()=>{},visualRenderer:port.visualRenderer,onVisualSourceActive:()=>mounted()}));
  await ready;
  const frames = async () => { for(let i=0;i<5;i++) await new Promise(requestAnimationFrame); };
  await frames();
  const view = {visual_revision:1,digest:'a'.repeat(64),annotations:[],focus:{group_id:'pair',binding_ref:'binding',owner_key:'owner',mode:'pulse',resolved_targets:{entity_ids:['B','C','A'],triangles:{left:['A','B','C'],right:['A','B','C']}}}};
  let receipts=0;
  await port.visualRenderer.render(view,{sessionId:'offline',executionKey:'focus',visualRevision:1,targetDigest:view.digest,operation:'entrance-complete',pulseIds:['focus:pair'],abort:new AbortController().signal}).then(()=>receipts++);
  const registry=host.querySelector('[data-visual-registry]');
  const pulse=registry.querySelector('[data-visual-pulse]');
  const read=()=>registry.querySelector('[data-visual-id="focus:pair/triangle/0"] path').getAttribute('d');
  const board=Object.values(JXG.boards).find(b=>host.contains(b.containerObj));
  if (!board) throw new Error(JSON.stringify({keys:Object.keys(JXG.boards),boards:Object.values(JXG.boards).map(b=>({container:b.container,id:b.id,obj:!!b.containerObj})),windowKeys:Object.keys(window.JXG?.boards??{})}));
  const aligned=()=>{
   const path=read().match(/-?\d+(?:\.\d+)?/g).map(Number);
   const points=['A','B','C'].map(id=>board.objectsList.find(o=>o.elType==='point'&&o.name===id));
   for(let i=0;i<3;i++)if(Math.hypot(path[i*2]-points[i].coords.scrCoords[1],path[i*2+1]-points[i].coords.scrCoords[2])>1)throw new Error('overlay detached from board point');
  };
  aligned(); const initial=read();
  host.style.width='390px'; await frames(); aligned(); const resized=read();
  if(initial===resized)throw new Error('resize did not reproject');
  const box=board.getBoundingBox();const cx=(box[0]+box[2])/2,cy=(box[1]+box[3])/2;
  board.setBoundingBox([cx+(box[0]-cx)*1.2,cy+(box[1]-cy)*1.2,cx+(box[2]-cx)*1.2,cy+(box[3]-cy)*1.2],false);
  await frames(); aligned(); const zoomed=read();
  if(zoomed===resized)throw new Error('zoom did not reproject');
  if(registry.querySelector('[data-visual-pulse]')!==pulse||host.getAnimations({subtree:true}).length||receipts!==1)throw new Error('layout restarted action or pulse');
  const during={sessionId:'offline',executionKey:'focus-mid-zoom',visualRevision:1,targetDigest:view.digest,operation:'entrance-complete',pulseIds:['focus:pair'],abort:new AbortController().signal};
  const active=port.visualRenderer.render(view,during);await frames();
  const activePulse=registry.querySelector('[data-visual-pulse]');
  const nextBox=board.getBoundingBox();
  board.setBoundingBox([nextBox[0]-1,nextBox[1]+1,nextBox[2]+1,nextBox[3]-1],false);
  await frames();aligned();await active;
  const retryStart=performance.now();await port.visualRenderer.render(view,during);
  if(performance.now()-retryStart>300||host.getAnimations({subtree:true}).length||registry.querySelector('[data-visual-pulse]')!==activePulse)throw new Error('mid-pulse reflow retry replayed or replaced effects');
  return {status:'passed',receipts,resizeAligned:true,zoomAligned:true,pulseReplayed:false,midPulseZoomRetry:true,initial,resized,zoomed};
 });
 await page.screenshot({path:`${output}/canvas.png`});
 writeFileSync(`${output}/canvas.json`,JSON.stringify(result,null,2)); console.log(JSON.stringify(result));
} finally {await browser.close();}
